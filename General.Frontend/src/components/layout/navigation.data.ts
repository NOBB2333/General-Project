export interface NavigationChild {
  label: string;
  badge?: number;
  view?: AppView;
}

export interface NavigationItem {
  label: string;
  icon: Component;
  badge?: number | string;
  children?: NavigationChild[];
  core?: boolean;
  settingsSummary?: string;
  settingsCount?: number;
  settingsChildren?: string[];
  view?: AppView;
}

function children(...entries: string[]): NavigationChild[] {
  return entries.map((entry) => {
    const match = entry.match(/^(.*) (\d+)$/);
    return match ? { label: match[1]!, badge: Number(match[2]) } : { label: entry };
  });
}

